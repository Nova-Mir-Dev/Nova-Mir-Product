export function generateCache(config: BootConfig): GeneratedFile[] {
  if (config.cache === 'none') return []
  const isUpstash = config.cache === 'upstash-redis'
  return [
    {
      path: 'lib/cache.ts',
      content: isUpstash ? cacheUpstashContent : cacheMemoryContent,
    },
  ]
}

