function generateAgentsMd(config: BootConfig): string {
  const hasCompliance = config.targetMarkets.length > 0

  const securitySkills: string[] = []
  if (config.payments !== 'none') {
    securitySkills.push(
      '- security-and-hardening: For payment and data-handling code',
    )
  }
  if (config.targetMarkets.some((m) => ['eu', 'uk'].includes(m))) {
    securitySkills.push(
      '- security-and-hardening: For GDPR-sensitive data handling',
    )
  }
  if (securitySkills.length === 0) {
    securitySkills.push(
      '- security-and-hardening: For auth, payment, and data-handling code',
    )
  }

  const complianceSection = hasCompliance
    ? `### Compliance-First Architecture

This project enforces a compliance-first approach:

1. **Compliance is automatic, not optional.** Privacy regulations, security headers, access controls, and data protection measures are auto-generated based on configuration.
2. **Cookie consent is trigger-based.** Generated only when tracking level > minimal AND target markets require it.
3. **Optimal defaults, flexible override.** Security-related options default to the strongest reasonable setting.
4. **Constraint warnings during transitions.** Track timing-sensitive constraints separately from logic errors.
5. **The compliance audit at generation time is the source of truth.`
    : `### Compliance-First Architecture

This project is built with a compliance-aware foundation:

1. **Security-first defaults.** All security-related options default to the strongest reasonable setting.
2. **Constraint validation.** Configuration consistency is validated at every step.
3. **The compliance audit at generation time is the source of truth.`

  return `# AGENTS.md

## Project Overview
${config.projectName}${config.projectDescription ? ` — ${config.projectDescription}` : ''} — generated by the Project Bootstrapper. A full-stack TypeScript application built with ${frameworkLabel(config.framework)}.

## Tool-First Philosophy

This project prioritizes tools, scripts, and pure logic over agentic work. Agents are expensive in tokens and slow to iterate. Use them only where they add unique value.

| Task | Use | Why |
|------|-----|-----|
| Type checking | npm run typecheck | Compiler — 0 tokens |
| Linting | npm run lint | Linter — 0 tokens |
| Formatting | npm run format | Formatter — 0 tokens |
| Build verification | npm run build | Bundler — 0 tokens |
| Spec writing | Agent (spec-driven-development) | Requires reasoning |
| Architectural decisions | Agent (doubt-driven-development) | Requires judgment |
| Code review | Agent (code-review-and-quality) | Requires multi-axis analysis |
| Debugging | Agent (debugging-and-error-recovery) | Requires hypothesis testing |
| Design/polish | Agent (impeccable) | Requires taste |

**Rule of thumb**: If a script can do it, write a script. Only invoke an agent when the task requires reasoning, judgment, or creative decision-making.

### Agent Invocation Policy

1. Try a script first. Is there a tool that can do this?
2. Try pure logic. Is this a simple computation?
3. Use an agent. Only if #1 and #2 don't apply.
4. Load the right skill. Always invoke the relevant skill before starting agent work.
5. Return to tools. Agent output should feed back into scripts for verification.

## Directory Structure (Co-Location)

\`\`\`
src/
├── app/                    # Next.js App Router — route segments only
│   ├── layout.tsx          # Root layout (ThemeProvider, fonts, metadata)
│   ├── globals.css         # Reset + base styles only (no component CSS)
│   ├── _components/        # Private components (underscore = not a route)
│   └── page.tsx            # Route entry (thin — re-exports feature)
├── features/               # Feature modules — self-contained
│   └── {feature}/
│       ├── types.ts        # Feature-specific types
│       ├── constraints.ts  # Validation / business logic
│       ├── {feature}.tsx   # Main component (orchestrator)
│       ├── {feature}.module.css  # Co-located styles
│       ├── compliance/     # Sub-domain of the feature
│       ├── steps/          # Sub-components used by the feature
│       └── use-{feature}.ts  # Custom hook (state management)
└── lib/                    # Shared utilities
    ├── db.ts               # Database client
    ├── auth.ts             # Auth configuration
    └── utils.ts            # Common helpers
\`\`\`

**Rules:**
1. Every feature lives in src/features/{feature-name}/ — self-contained, no cross-feature coupling
2. Step/sub-components go in {feature}/steps/ — one component per file, thin wrappers
3. Business logic extracted into hooks (use-{feature}.ts) — components only render
4. Route entry (app/page.tsx) MUST be a single re-export line — never inline a page component
5. CSS modules co-located with their component — never a global stylesheet per feature
6. Never dump all components in a single folder — sub-folders for logical groups
7. No index.ts barrel files in step folders — import directly from the file

## Development Rules

${complianceSection}

### Core Rules

1. Always use azimuth-ui components — never write raw \`<button>\`, \`<input>\`, \`<p>\`, \`<h1>\` etc.
2. All UI must use ThemeProvider tokens (--azimuth-* CSS variables)
3. Every component must be accessible (WCAG 2.2 AA)
4. Use the incremental-implementation skill for all multi-file changes
5. Use subagents for any work block that can run independently

### Code Style

- No comments unless explaining non-obvious business logic
- Three similar lines beat a premature abstraction. Use the concrete pattern three times before extracting.
- Use azimuth-ui's Text component for all typography (size, weight, color props)
- Use azimuth-ui's Button for all buttons (variant, size props)
- CSS modules for feature-specific layout; globals.css only for reset and base
- Component files named for what they render (not index.tsx)
- Props interfaces co-located with their component (not in a separate types file unless shared)

### Quality Gates (Must Pass Before Merge)

1. TypeScript: npm run typecheck — zero errors
2. Build: npm run build — must succeed
3. Lint: npm run lint — zero warnings
4. Format: npm run format — all files formatted
5. Tests: npm test — all passing
6. A11y: New UI passes WCAG 2.2 AA check${config.hasPublicApi ? '\n7. API: OpenAPI spec matches implementation — no drift' : ''}

### Must-Use Skills

- full-audit: Run before releases, after major changes, or on request
- a11y-audit: After any UI change, audit for WCAG 2.2 AA compliance
${securitySkills.join('\n')}
- impeccable: For any UI design or styling decisions. All interfaces must pass impeccable standards.
- spec-driven-development: BEFORE implementing any new feature
- test-driven-development: For any logic code. Write tests first
- code-review-and-quality: Before merging any change
- incremental-implementation: For any change touching multiple files
- doubt-driven-development: For compliance and security-sensitive code

### Anti-Patterns

- DO NOT write raw HTML elements — use azimuth components
- DO NOT invent new color tokens — use --azimuth-color-* variables
- DO NOT skip compliance auditing for any configurator change
- DO NOT merge without code-review-and-quality first
- DO NOT create mega-components — split into step/sub components after ~100 lines
- DO NOT put business logic in components — extract into hooks
- DO NOT use barrel index.ts files in sub-folders — import from the source file

${generateProjectContext(config)}
`
}

function generateProjectContext(config: BootConfig): string {
  const sections: string[] = []

  sections.push(`## Project Context

Generated for: ${config.projectName}
Framework: ${config.framework}
Hosting: ${config.hosting}
Database: ${config.database} (${config.databaseProvider})
Auth: ${config.auth}
Target Markets: ${config.targetMarkets.join(', ')}
`)

  // Schema tables
  const tables: string[] = []
  if (config.auditLogging) tables.push('audit_logs')
  if (config.apiKeyAuth) tables.push('api_keys')
  if (config.appointments) tables.push('appointments')
  if (config.eSignature) tables.push('documents', 'signatures')
  if (config.auth !== 'none') tables.push('sessions')
  if (config.payments !== 'none') tables.push('payments')
  if (tables.length > 0) {
    sections.push(`### Database Tables
- users (core user accounts)
${tables.map((t) => `- ${t}`).join('\n')}
`)
  }

  // API routes
  const apiRoutes: string[] = []
  if (config.payments === 'stripe')
    apiRoutes.push('POST /api/stripe — Stripe webhook handler')
  if (config.appointments)
    apiRoutes.push('GET/POST /api/appointments — Manage appointments')
  if (config.eSignature)
    apiRoutes.push('GET/POST /api/documents — Document management')
  if (config.apiKeyAuth)
    apiRoutes.push('GET/POST /api/admin/api-keys — API key management')
  if (config.inAppNotifications)
    apiRoutes.push('GET/POST /api/notifications — In-app notifications')
  if (config.uptimeMonitoring) apiRoutes.push('GET /api/health — Health check')
  if (config.dataExport) apiRoutes.push('GET /api/export — Data export')
  if (config.auditLogging)
    apiRoutes.push('GET /api/compliance/data-access — DSAR access endpoint')
  if (config.auditLogging)
    apiRoutes.push(
      'POST /api/compliance/data-deletion — DSAR deletion endpoint',
    )
  if (config.auditLogging)
    apiRoutes.push(
      'POST /api/compliance/data-correction — DSAR correction endpoint',
    )
  if (config.hasCrudEndpoints)
    apiRoutes.push('GET/POST /api/crud/:entity — Generic CRUD scaffold')
  if (apiRoutes.length > 0) {
    sections.push(`### API Routes
${apiRoutes.map((r) => `- ${r}`).join('\n')}
`)
  }

  // Env var summary
  sections.push(`### Required Environment Variables
See \`.env.example\` for the full list. Key variables to set:\n- Database: NEXT_PUBLIC_SUPABASE_URL, NEXT_PUBLIC_SUPABASE_ANON_KEY${config.payments === 'stripe' ? '\n- Payments: STRIPE_SECRET_KEY, NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY' : ''}${config.emailProvider !== 'none' ? '\n- Email: RESEND_API_KEY (or equivalent)' : ''}${config.monitoring === 'sentry' ? '\n- Monitoring: NEXT_PUBLIC_SENTRY_DSN, SENTRY_AUTH_TOKEN' : ''}${config.communicationPlatforms.includes('slack') ? '\n- Slack: SLACK_BOT_TOKEN, SLACK_SIGNING_SECRET' : ''}${config.logManagement === 'axiom' ? '\n- Logging: AXIOM_API_TOKEN, NEXT_PUBLIC_AXIOM_DATASET' : ''}
`)

  // Compliance note
  if (config.targetMarkets.length > 0) {
    sections.push(`### Compliance
Applicable regulations for selected markets (${config.targetMarkets.join(', ')}):
- See docs/COMPLIANCE.md and docs/PRIVACY.md for full details
- DSAR endpoints are available at /api/compliance/* for data access/deletion/correction requests
`)
  }

  return sections.join('\n').trim()
}

