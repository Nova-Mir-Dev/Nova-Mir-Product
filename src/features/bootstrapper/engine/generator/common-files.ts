function getEnvVarDescriptions(config: BootConfig): Record<string, string> {
  const vars: Record<string, string> = {}

  vars['NEXT_PUBLIC_SUPABASE_URL'] = 'Supabase project URL'
  vars['NEXT_PUBLIC_SUPABASE_ANON_KEY'] =
    'Supabase anonymous key (safe for client)'
  vars['SUPABASE_SERVICE_ROLE_KEY'] = 'Supabase service role key (server-only)'

  switch (config.databaseProvider) {
    case 'supabase':
      vars['DATABASE_URL'] = 'PostgreSQL connection string (Supabase managed)'
      break
    case 'planetscale':
      vars['DATABASE_URL'] = 'MySQL connection string (PlanetScale managed)'
      break
    case 'turso':
      vars['DATABASE_URL'] = 'libSQL/Turso database URL'
      vars['TURSO_AUTH_TOKEN'] = 'Turso authentication token'
      break
    case 'neon':
      vars['DATABASE_URL'] = 'PostgreSQL connection string (Neon serverless)'
      break
    case 'atlas':
      vars['MONGODB_URI'] = 'MongoDB Atlas connection string'
      break
    default:
      vars['DATABASE_URL'] = 'Database connection string'
  }

  switch (config.auth) {
    case 'jwt':
      vars['JWT_SECRET'] = 'Secret key for signing JWTs'
      break
    case 'next-auth':
      vars['AUTH_SECRET'] = 'Auth.js secret for encrypting sessions'
      vars['AUTH_URL'] = 'Base URL of the application'
      if (config.ssoProviders.includes('google')) {
        vars['GOOGLE_CLIENT_ID'] = 'Google OAuth client ID'
        vars['GOOGLE_CLIENT_SECRET'] = 'Google OAuth client secret'
      }
      if (config.ssoProviders.includes('github')) {
        vars['GITHUB_CLIENT_ID'] = 'GitHub OAuth client ID'
        vars['GITHUB_CLIENT_SECRET'] = 'GitHub OAuth client secret'
      }
      if (config.ssoProviders.includes('microsoft')) {
        vars['AZURE_AD_CLIENT_ID'] = 'Azure AD application client ID'
        vars['AZURE_AD_CLIENT_SECRET'] = 'Azure AD application client secret'
        vars['AZURE_AD_TENANT_ID'] = 'Azure AD tenant ID'
      }
      if (config.ssoProviders.includes('apple')) {
        vars['APPLE_CLIENT_ID'] = 'Apple Sign In service ID'
        vars['APPLE_CLIENT_SECRET'] = 'Apple Sign In private key'
      }
      break
    case 'auth0':
      vars['AUTH0_SECRET'] = 'Auth0 secret for encrypting sessions'
      vars['AUTH0_ISSUER_BASE_URL'] = 'Auth0 tenant domain URL'
      vars['AUTH0_BASE_URL'] = 'Base URL of the application'
      vars['AUTH0_CLIENT_ID'] = 'Auth0 application client ID'
      vars['AUTH0_CLIENT_SECRET'] = 'Auth0 application client secret'
      break
  }

  if (config.payments === 'stripe') {
    vars['STRIPE_SECRET_KEY'] = 'Stripe secret key (server-only)'
    vars['STRIPE_WEBHOOK_SECRET'] = 'Stripe webhook signing secret'
    vars['NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY'] =
      'Stripe publishable key (safe for client)'
  }

  if (config.emailProvider === 'resend') {
    vars['RESEND_API_KEY'] = 'Resend API key'
    vars['EMAIL_FROM'] = 'From address for transactional emails'
  }

  if (config.monitoring === 'sentry') {
    vars['NEXT_PUBLIC_SENTRY_DSN'] = 'Sentry DSN for client-side error tracking'
    vars['SENTRY_AUTH_TOKEN'] = 'Sentry auth token for sourcemap uploads'
    vars['SENTRY_ORG'] = 'Sentry organisation slug'
    vars['SENTRY_PROJECT'] = 'Sentry project slug'
  }

  if (config.communicationPlatforms.includes('slack')) {
    vars['SLACK_BOT_TOKEN'] = 'Slack bot token for messaging'
    vars['SLACK_SIGNING_SECRET'] = 'Slack signing secret for verifying requests'
  }

  if (config.logManagement === 'axiom') {
    vars['NEXT_PUBLIC_AXIOM_DATASET'] = 'Axiom dataset name for log ingestion'
    vars['AXIOM_API_TOKEN'] = 'Axiom API token for sending logs'
  }

  if (config.corsEnabled) {
    vars['CORS_ORIGINS'] = 'Allowed CORS origins (comma-separated, * for all)'
  }

  if (config.smsProvider === 'twilio') {
    vars['TWILIO_ACCOUNT_SID'] = 'Twilio account SID'
    vars['TWILIO_AUTH_TOKEN'] = 'Twilio auth token'
    vars['TWILIO_PHONE_NUMBER'] = 'Twilio phone number for sending SMS'
  }

  if (config.rateLimiting === 'upstash') {
    vars['UPSTASH_REDIS_URL'] = 'Upstash Redis URL for rate limiting'
    vars['UPSTASH_REDIS_TOKEN'] = 'Upstash Redis token for rate limiting'
  }

  return vars
}

function buildFeaturesList(config: BootConfig): string {
  const items: string[] = []
  if (config.auth !== 'none') {
    let authDesc = `- **Authentication** — ${config.auth}`
    if (config.totpEnabled) authDesc += ' with TOTP/2FA'
    if (config.passkeysEnabled) authDesc += ' + Passkeys'
    items.push(authDesc)
  }
  if (config.payments !== 'none')
    items.push(`- **Payments** — ${config.payments}`)
  if (config.fileStorage !== 'none')
    items.push(`- **File Storage** — ${config.fileStorage}`)
  if (config.emailProvider !== 'none')
    items.push(`- **Email** — ${config.emailProvider}`)
  if (config.monitoring !== 'none')
    items.push(`- **Monitoring** — ${config.monitoring}`)
  if (config.communicationPlatforms.length > 0)
    items.push(
      `- **Integrations** — ${config.communicationPlatforms.join(', ')}`,
    )
  if (config.featureFlags) items.push('- **Feature Flags**')
  if (config.auditLogging) items.push('- **Audit Logging**')
  return items.join('\n')
}

