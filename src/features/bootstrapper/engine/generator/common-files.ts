function frameworkLabel(framework: BootConfig['framework']): string {
  const labels: Record<typeof framework, string> = {
    nextjs: 'Next.js 15 (App Router)',
    'vite-react': 'Vite + React 19',
    remix: 'Remix',
    astro: 'Astro',
  }
  return labels[framework]
}

function generateEnvExample(config: BootConfig): string {
  const lines: string[] = []

  lines.push(
    '# Supabase',
    'NEXT_PUBLIC_SUPABASE_URL=',
    'NEXT_PUBLIC_SUPABASE_ANON_KEY=',
    'SUPABASE_SERVICE_ROLE_KEY=  # Server-only — never expose to client',
  )

  switch (config.databaseProvider) {
    case 'supabase':
      lines.push(
        'DATABASE_URL=postgresql://postgres:[PASSWORD]@db.[PROJECT_REF].supabase.co:5432/postgres',
      )
      break
    case 'planetscale':
      lines.push(
        'DATABASE_URL=mysql://[USERNAME]:[PASSWORD]@[HOST]/[DATABASE]?ssl=%7B%22rejectUnauthorized%22%3Atrue%7D',
      )
      break
    case 'turso':
      lines.push('DATABASE_URL=libsql://[DATABASE]-[ORGANIZATION].turso.io')
      lines.push('TURSO_AUTH_TOKEN=')
      break
    case 'neon':
      lines.push(
        'DATABASE_URL=postgresql://[USERNAME]:[PASSWORD]@[HOST]/[DATABASE]?sslmode=require',
      )
      break
    case 'atlas':
      lines.push(
        'MONGODB_URI=mongodb+srv://[USERNAME]:[PASSWORD]@[CLUSTER].mongodb.net/[DATABASE]?retryWrites=true&w=majority',
      )
      break
    default:
      break
  }
  lines.push('')

  switch (config.auth) {
    case 'jwt':
      lines.push('', 'JWT_SECRET=your-secret-at-least-32-chars')
      break
    case 'next-auth': {
      lines.push(
        '',
        'AUTH_SECRET=your-auth-secret',
        'AUTH_URL=http://localhost:3000',
      )
      for (const p of config.ssoProviders) {
        switch (p) {
          case 'google':
            lines.push('GOOGLE_CLIENT_ID=', 'GOOGLE_CLIENT_SECRET=')
            break
          case 'github':
            lines.push('GITHUB_CLIENT_ID=', 'GITHUB_CLIENT_SECRET=')
            break
          case 'microsoft':
            lines.push(
              'AZURE_AD_CLIENT_ID=',
              'AZURE_AD_CLIENT_SECRET=',
              'AZURE_AD_TENANT_ID=',
            )
            break
          case 'apple':
            lines.push('APPLE_CLIENT_ID=', 'APPLE_CLIENT_SECRET=')
            break
        }
      }
      break
    }
    case 'auth0':
      lines.push(
        '',
        'AUTH0_SECRET=long-random-secret',
        'AUTH0_ISSUER_BASE_URL=https://[tenant].auth0.com',
        'AUTH0_BASE_URL=http://localhost:3000',
        'AUTH0_CLIENT_ID=',
        'AUTH0_CLIENT_SECRET=',
      )
      break
  }

  if (config.payments === 'stripe') {
    lines.push(
      '',
      '# Stripe',
      'STRIPE_SECRET_KEY=sk_live_',
      'STRIPE_WEBHOOK_SECRET=whsec_',
      'NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY=pk_',
    )
  }

  if (config.emailProvider === 'resend') {
    lines.push(
      '',
      '# Email (Resend)',
      'RESEND_API_KEY=re_',
      `EMAIL_FROM=hello@${config.projectName}.com`,
    )
  }

  if (config.smsProvider === 'twilio') {
    lines.push(
      '',
      '# Twilio',
      'TWILIO_ACCOUNT_SID=',
      'TWILIO_AUTH_TOKEN=',
      'TWILIO_PHONE_NUMBER=',
    )
  }

  if (config.monitoring === 'sentry') {
    lines.push(
      '',
      '# Sentry',
      'NEXT_PUBLIC_SENTRY_DSN=',
      'SENTRY_AUTH_TOKEN=',
      'SENTRY_ORG=',
      'SENTRY_PROJECT=',
    )
  }

  if (config.communicationPlatforms.includes('slack')) {
    lines.push('', '# Slack', 'SLACK_BOT_TOKEN=xoxb-', 'SLACK_SIGNING_SECRET=')
  }

  if (config.logManagement === 'axiom') {
    lines.push('', '# Axiom', 'NEXT_PUBLIC_AXIOM_DATASET=', 'AXIOM_API_TOKEN=')
  }

  if (config.corsEnabled) {
    lines.push('', '# CORS', 'CORS_ORIGINS=http://localhost:3000')
  }

  if (config.rateLimiting === 'upstash' || config.cache === 'upstash-redis') {
    lines.push(
      '',
      '# Upstash Redis',
      'UPSTASH_REDIS_URL=',
      'UPSTASH_REDIS_TOKEN=',
    )
  }

  return lines.join('\n')
}

